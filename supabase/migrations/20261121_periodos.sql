-- Fase 2 de períodos: resultado de cada KPI por mes, fecha límite para calificar y cierre de períodos en el servidor.
-- Ejecutar una vez en Supabase → SQL Editor (después de 20261120_cierres_oficiales.sql).
--
-- Modelo:
--  * El período de gestión es el mes calendario ('AAAA-MM').
--  * resultados_kpi guarda un resultado por KPI y por mes. Los KPI mensuales se evalúan cada mes; los trimestrales,
--    semestrales y anuales registran su AVANCE cada mes y se evalúan en el último mes de su ventana.
--  * Los líderes pueden calificar un mes hasta su último día + dias_limite_calificacion (configurable).
--  * periodos_cerrados marca los meses cerrados por el Admin: sus resultados ya no se pueden modificar.
-- Todo se lee y escribe desde el servidor (/api/datos, /api/resultados, /api/periodos) con la service role.

-- 1. Fecha límite para calificar (días después del fin de mes)
alter table public.configuracion_empresa
  add column if not exists dias_limite_calificacion integer not null default 5
  check (dias_limite_calificacion between 0 and 28);

-- 2. Resultado de cada KPI por mes
create table if not exists public.resultados_kpi (
  id             bigint generated by default as identity primary key,
  indicador_id   bigint not null references public.indicadores(id) on delete cascade,
  empleado_id    bigint not null,
  empresa_id     bigint not null,
  periodo        text   not null check (periodo ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  resultado      numeric not null,
  progreso       numeric(5, 2) not null check (progreso between 0 and 100),
  registrado_por uuid,
  updated_at     timestamptz not null default now(),
  unique (indicador_id, periodo)
);
create index if not exists resultados_kpi_empresa_periodo_idx on public.resultados_kpi (empresa_id, periodo);
create index if not exists resultados_kpi_empleado_idx on public.resultados_kpi (empleado_id, periodo);
alter table public.resultados_kpi enable row level security;  -- sin políticas: solo el servidor

-- 3. Meses cerrados y reaperturas (auditoría)
create table if not exists public.periodos_cerrados (
  empresa_id  bigint not null,
  periodo     text   not null check (periodo ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  cerrado_en  timestamptz not null default now(),
  cerrado_por uuid,
  primary key (empresa_id, periodo)
);
alter table public.periodos_cerrados enable row level security;

create table if not exists public.periodos_reaperturas (
  id            bigint generated by default as identity primary key,
  empresa_id    bigint not null,
  periodo       text   not null,
  motivo        text   not null check (btrim(motivo) <> ''),
  reabierto_por uuid,
  reabierto_en  timestamptz not null default now()
);
alter table public.periodos_reaperturas enable row level security;

-- 4. Un mes cerrado no admite cambios en sus resultados (respaldo en BD de la regla de la app)
create or replace function public.bloquear_resultados_periodo_cerrado()
returns trigger
language plpgsql
as $$
declare
  v_empresa bigint := coalesce(new.empresa_id, old.empresa_id);
  v_periodo text   := coalesce(new.periodo, old.periodo);
begin
  -- Si se elimina el KPI completo (borrado en cascada) se permite: la foto oficial del mes ya está en historico_cumplimiento
  if tg_op = 'DELETE' and not exists (select 1 from public.indicadores where id = old.indicador_id) then
    return old;
  end if;
  if exists (select 1 from public.periodos_cerrados where empresa_id = v_empresa and periodo = v_periodo) then
    raise exception 'El período % está cerrado: sus resultados no se pueden modificar.', v_periodo
      using errcode = 'P0001';
  end if;
  if tg_op = 'UPDATE' and old.periodo <> new.periodo
     and exists (select 1 from public.periodos_cerrados where empresa_id = old.empresa_id and periodo = old.periodo) then
    raise exception 'El período % está cerrado.', old.periodo using errcode = 'P0001';
  end if;
  return coalesce(new, old);
end;
$$;

drop trigger if exists bloquear_resultados_periodo_cerrado on public.resultados_kpi;
create trigger bloquear_resultados_periodo_cerrado
  before insert or update or delete on public.resultados_kpi
  for each row execute function public.bloquear_resultados_periodo_cerrado();

-- 5. Datos existentes
-- 5a. Los meses con cierre oficial (fase 1) pasan a periodos_cerrados. La etiqueta es "Noviembre 2026".
insert into public.periodos_cerrados (empresa_id, periodo, cerrado_en)
select h.empresa_id,
       split_part(h.periodo, ' ', 2) || '-' || lpad(m.n::text, 2, '0'),
       min(h.fecha_corte)
from public.historico_cumplimiento h
join (values ('enero', 1), ('febrero', 2), ('marzo', 3), ('abril', 4), ('mayo', 5), ('junio', 6), ('julio', 7),
             ('agosto', 8), ('septiembre', 9), ('octubre', 10), ('noviembre', 11), ('diciembre', 12)) as m(nombre, n)
  on lower(split_part(h.periodo, ' ', 1)) = m.nombre
where h.oficial and h.empresa_id is not null and split_part(h.periodo, ' ', 2) ~ '^[0-9]{4}$'
group by 1, 2
on conflict do nothing;

-- 5b. El valor que hoy tiene cada KPI pasa a ser su resultado del mes en curso (si ese mes no está cerrado)
insert into public.resultados_kpi (indicador_id, empleado_id, empresa_id, periodo, resultado, progreso)
select i.id, i.empleado_id, e.empresa_id, to_char(now(), 'YYYY-MM'),
       coalesce(i.resultado_actual, 0), least(greatest(coalesce(i.progreso, 0), 0), 100)
from public.indicadores i
join public.empleados e on e.id = i.empleado_id
where (coalesce(i.resultado_actual, 0) <> 0 or coalesce(i.progreso, 0) > 0)
  and not exists (select 1 from public.periodos_cerrados pc where pc.empresa_id = e.empresa_id and pc.periodo = to_char(now(), 'YYYY-MM'))
on conflict (indicador_id, periodo) do nothing;
