-- OKR en cascada: Empresa → Área → Persona, y peso de cada KPI en el cumplimiento de la persona.
-- Ejecutar una vez en Supabase → SQL Editor (después de 20261122_liderazgo_unico.sql).
--
-- Modelo:
--  * okr_objetivos: objetivo ANUAL. area_id null = objetivo de la empresa. Un objetivo de área se alinea a un
--    resultado clave del nivel superior (kr_padre_id): de la empresa si el área es principal, del área superior si es sub-área.
--  * okr_resultados_clave: resultado clave (KR) de un TRIMESTRE. 'medido' = tiene su meta y resultado propios;
--    'calculado' = promedio de lo que tiene vinculado (KPIs de personas y objetivos de área alineados).
--  * indicadores.kr_id: KR (de su área) al que aporta el KPI. Sin KR = KPI "operativo".
--  * indicadores.peso: peso del KPI en el cumplimiento de la persona (null = todos pesan igual).
-- Todo se lee y escribe desde el servidor (/api/okr) con la service role; el avance se calcula allí.

create table if not exists public.okr_objetivos (
  id              bigint generated by default as identity primary key,
  empresa_id      bigint  not null,
  area_id         bigint  references public.areas(id) on delete cascade,
  anio            integer not null check (anio between 2000 and 2100),
  titulo          text    not null check (btrim(titulo) <> ''),
  descripcion     text,
  kr_padre_id     bigint,
  responsable_id  bigint  references public.empleados(id) on delete set null,
  orden           integer not null default 0,
  creado_por      uuid,
  created_at      timestamptz not null default now()
);

create table if not exists public.okr_resultados_clave (
  id               bigint generated by default as identity primary key,
  objetivo_id      bigint  not null references public.okr_objetivos(id) on delete cascade,
  empresa_id       bigint  not null,
  titulo           text    not null check (btrim(titulo) <> ''),
  trimestre        smallint not null check (trimestre between 1 and 4),
  tipo_medicion    text    not null default 'calculado' check (tipo_medicion in ('calculado', 'medido')),
  -- Solo para 'medido'
  valor_inicial    numeric not null default 0,
  meta             numeric,
  unidad           text,
  direccion        text    not null default 'creciente' check (direccion in ('creciente', 'decreciente')),
  resultado_actual numeric,
  actualizado_en   timestamptz,
  orden            integer not null default 0,
  created_at       timestamptz not null default now(),
  constraint okr_kr_medido_con_meta check (tipo_medicion = 'calculado' or meta is not null)
);

-- La alineación apunta a un KR (se define después de crear la tabla de KR)
do $$ begin
  alter table public.okr_objetivos
    add constraint okr_objetivos_kr_padre_fk foreign key (kr_padre_id) references public.okr_resultados_clave(id) on delete set null;
exception when duplicate_object then null; end $$;

create index if not exists okr_objetivos_empresa_anio_idx on public.okr_objetivos (empresa_id, anio);
create index if not exists okr_objetivos_kr_padre_idx on public.okr_objetivos (kr_padre_id);
create index if not exists okr_kr_objetivo_idx on public.okr_resultados_clave (objetivo_id, trimestre);

alter table public.okr_objetivos enable row level security;        -- sin políticas: solo el servidor
alter table public.okr_resultados_clave enable row level security;

-- KPIs: vínculo al KR y peso en la persona
alter table public.indicadores add column if not exists kr_id bigint references public.okr_resultados_clave(id) on delete set null;
alter table public.indicadores add column if not exists peso  numeric(5, 2) check (peso is null or (peso > 0 and peso <= 100));
create index if not exists indicadores_kr_idx on public.indicadores (kr_id);
