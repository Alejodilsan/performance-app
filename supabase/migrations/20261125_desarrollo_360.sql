-- Desarrollo después de la 360: plan de desarrollo individual (PDI 70-20-10), check-ins mensuales y pulso de
-- seguimiento a mitad de ciclo. Ejecutar una vez en Supabase → SQL Editor (después de 20261124_evaluacion_360.sql).
--
-- Modelo:
--  * pdi_objetivos: objetivo de desarrollo de una persona, idealmente ligado a una competencia de un ciclo 360.
--  * pdi_acciones: acciones del objetivo según 70-20-10: 'experiencia' (aprender haciendo), 'relacion' (mentoría,
--    feedback, pares) y 'formacion' (cursos, lecturas). El avance del objetivo = % de acciones completadas.
--  * pdi_checkins: conversación de seguimiento mensual (una por persona y mes 'AAAA-MM').
--  * ev360_pulsos: pulso de un ciclo con resultados. ev360_pulso_asignaciones: quién responde (los mismos evaluadores
--    que completaron la 360) y sobre qué competencias (las del PDI, congeladas al lanzar). ev360_pulso_respuestas: 1–5
--    o null (no observado).
-- Todo se lee y escribe desde el servidor (/api/desarrollo y /api/evaluaciones): RLS sin políticas.

create table if not exists public.pdi_objetivos (
  id                 bigint generated by default as identity primary key,
  empresa_id         bigint  not null,
  empleado_id        bigint  not null references public.empleados(id) on delete cascade,
  ciclo_id           bigint  references public.ev360_ciclos(id) on delete set null,
  competencia_id     bigint,
  competencia        text,
  titulo             text    not null check (btrim(titulo) <> ''),
  resultado_esperado text,
  fecha_limite       date,
  estado             text    not null default 'en_curso' check (estado in ('en_curso', 'logrado', 'no_logrado', 'cancelado')),
  creado_por         bigint  references public.empleados(id) on delete set null,
  created_at         timestamptz not null default now(),
  actualizado_en     timestamptz not null default now()
);
create index if not exists pdi_objetivos_empleado_idx on public.pdi_objetivos (empresa_id, empleado_id);

create table if not exists public.pdi_acciones (
  id            bigint generated by default as identity primary key,
  objetivo_id   bigint  not null references public.pdi_objetivos(id) on delete cascade,
  empresa_id    bigint  not null,
  tipo          text    not null check (tipo in ('experiencia', 'relacion', 'formacion')),
  descripcion   text    not null check (btrim(descripcion) <> ''),
  fecha_limite  date,
  completada    boolean not null default false,
  completada_en timestamptz,
  orden         integer not null default 0
);
create index if not exists pdi_acciones_objetivo_idx on public.pdi_acciones (objetivo_id, orden);

create table if not exists public.pdi_checkins (
  id             bigint generated by default as identity primary key,
  empresa_id     bigint  not null,
  empleado_id    bigint  not null references public.empleados(id) on delete cascade,
  periodo        text    not null check (periodo ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  comentario     text    not null check (btrim(comentario) <> ''),
  proximos_pasos text,
  registrado_por bigint  references public.empleados(id) on delete set null,
  created_at     timestamptz not null default now(),
  unique (empleado_id, periodo)
);
create index if not exists pdi_checkins_empresa_idx on public.pdi_checkins (empresa_id, periodo);

create table if not exists public.ev360_pulsos (
  id         bigint generated by default as identity primary key,
  ciclo_id   bigint  not null unique references public.ev360_ciclos(id) on delete cascade,
  empresa_id bigint  not null,
  estado     text    not null default 'abierto' check (estado in ('abierto', 'cerrado')),
  cierra_el  date,
  abierto_en timestamptz not null default now()
);

create table if not exists public.ev360_pulso_asignaciones (
  id            bigint generated by default as identity primary key,
  pulso_id      bigint  not null references public.ev360_pulsos(id) on delete cascade,
  empresa_id    bigint  not null,
  evaluado_id   bigint  not null references public.empleados(id) on delete cascade,
  evaluador_id  bigint  not null references public.empleados(id) on delete cascade,
  relacion      text    not null check (relacion in ('auto', 'lider', 'par', 'colaborador')),
  -- Competencias del PDI al lanzar el pulso: [{ "id": 1, "nombre": "..." }]
  competencias  jsonb   not null,
  estado        text    not null default 'pendiente' check (estado in ('pendiente', 'completada')),
  comentario    text,
  completada_en timestamptz,
  unique (pulso_id, evaluado_id, evaluador_id)
);
create index if not exists ev360_pulso_asig_evaluador_idx on public.ev360_pulso_asignaciones (pulso_id, evaluador_id);

create table if not exists public.ev360_pulso_respuestas (
  asignacion_id  bigint   not null references public.ev360_pulso_asignaciones(id) on delete cascade,
  competencia_id bigint   not null,
  puntaje        smallint check (puntaje is null or puntaje between 1 and 5),
  primary key (asignacion_id, competencia_id)
);

alter table public.pdi_objetivos            enable row level security;  -- sin políticas: solo el servidor
alter table public.pdi_acciones             enable row level security;
alter table public.pdi_checkins             enable row level security;
alter table public.ev360_pulsos             enable row level security;
alter table public.ev360_pulso_asignaciones enable row level security;
alter table public.ev360_pulso_respuestas   enable row level security;
