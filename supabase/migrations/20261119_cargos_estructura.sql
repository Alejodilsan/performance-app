-- En la app la tabla sigue llamándose "puestos" (solo cambió el texto visible a "Cargo").
--
-- ⚠️ Antes de crear los índices únicos se revisa si ya hay duplicados ("Analista" / "analista " / "Análista").
--    Si los hay, el script se detiene SIN aplicar nada y lista cuáles son. Para verlos:
--
--      select empresa_id, public.normalizar_nombre(nombre) as clave, array_agg(id || ': ' || nombre)
--      from public.areas group by 1, 2 having count(*) > 1;
--
--      select empresa_id, public.normalizar_nombre(nombre) as clave, array_agg(id || ': ' || nombre)
--      from public.puestos group by 1, 2 having count(*) > 1;      -- (si ya existe area_id, agrúpalo también)
--
--    Unifícalos (mueve a los colaboradores al que se queda y borra/renombra el otro) y vuelve a ejecutar.

-- ------------------------------------------------------------------
-- 1. Normalización de nombres (debe coincidir con normalizarNombre() de lib/similitud.ts):
--    minúsculas, sin tildes, sin espacios al inicio/fin y espacios internos colapsados.
-- ------------------------------------------------------------------
create or replace function public.normalizar_nombre(p text)
returns text
language sql
immutable
parallel safe
as $$
  select regexp_replace(
    translate(lower(btrim(coalesce(p, ''))),
      'áàäâãåéèëêíìïîóòöôõúùüûñçý',
      'aaaaaaeeeeiiiiooooouuuuncy'),
    '\s+', ' ', 'g');
$$;

-- Si ya hay duplicados, se detiene aquí antes de cambiar nada.
do $$
declare
  v_areas text;
  v_cargos text;
begin
  select string_agg(format('empresa %s: %s', empresa_id, nombres), E'\n') into v_areas from (
    select empresa_id, string_agg(id || ' "' || nombre || '"', ', ' order by id) as nombres
    from public.areas group by empresa_id, public.normalizar_nombre(nombre) having count(*) > 1
  ) d;
  -- La primera vez puestos.area_id aún no existe: todos los cargos cuentan como "sin área"
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'puestos' and column_name = 'area_id') then
    execute $q$
      select string_agg(format('empresa %s, área %s: %s', empresa_id, coalesce(area_id::text, 'sin área'), nombres), E'\n') from (
        select empresa_id, area_id, string_agg(id || ' "' || nombre || '"', ', ' order by id) as nombres
        from public.puestos group by empresa_id, area_id, public.normalizar_nombre(nombre) having count(*) > 1
      ) d $q$ into v_cargos;
  else
    execute $q$
      select string_agg(format('empresa %s: %s', empresa_id, nombres), E'\n') from (
        select empresa_id, string_agg(id || ' "' || nombre || '"', ', ' order by id) as nombres
        from public.puestos group by empresa_id, public.normalizar_nombre(nombre) having count(*) > 1
      ) d $q$ into v_cargos;
  end if;
  if v_areas is not null or v_cargos is not null then
    raise exception E'Hay nombres duplicados. Unifícalos y vuelve a ejecutar.\nÁreas:\n%\nCargos:\n%',
      coalesce(v_areas, '(ninguna)'), coalesce(v_cargos, '(ninguno)');
  end if;
end $$;

-- ------------------------------------------------------------------
-- 2. Niveles de cargo (catálogo configurable por empresa: Operativo, Profesional, Jefatura…)
-- ------------------------------------------------------------------
create table if not exists public.niveles_cargo (
  id          bigint generated by default as identity primary key,
  empresa_id  bigint not null,
  nombre      text   not null check (btrim(nombre) <> ''),
  orden       integer not null default 0,
  created_at  timestamptz not null default now()
);
create unique index if not exists niveles_cargo_nombre_unico_idx
  on public.niveles_cargo (empresa_id, public.normalizar_nombre(nombre));

-- ¿El usuario actual pertenece a esa empresa? (security definer para no depender de las políticas de perfiles)
create or replace function public.es_miembro_de_empresa(p_empresa_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.perfiles where id = auth.uid() and empresa_id = p_empresa_id);
$$;

alter table public.niveles_cargo enable row level security;
drop policy if exists niveles_cargo_select on public.niveles_cargo;
drop policy if exists niveles_cargo_admin_insert on public.niveles_cargo;
drop policy if exists niveles_cargo_admin_update on public.niveles_cargo;
drop policy if exists niveles_cargo_admin_delete on public.niveles_cargo;
create policy niveles_cargo_select on public.niveles_cargo
  for select to authenticated using (public.es_miembro_de_empresa(empresa_id));
create policy niveles_cargo_admin_insert on public.niveles_cargo
  for insert to authenticated with check (public.es_admin_de_empresa(empresa_id));
create policy niveles_cargo_admin_update on public.niveles_cargo
  for update to authenticated using (public.es_admin_de_empresa(empresa_id)) with check (public.es_admin_de_empresa(empresa_id));
create policy niveles_cargo_admin_delete on public.niveles_cargo
  for delete to authenticated using (public.es_admin_de_empresa(empresa_id));

-- ------------------------------------------------------------------
-- 3. Datos del cargo. area_id es obligatoria en la app; queda nullable para los cargos que ya
--    existían (la app pide completarla al editarlos).
-- ------------------------------------------------------------------
alter table public.puestos add column if not exists area_id     bigint references public.areas(id) on delete restrict;
alter table public.puestos add column if not exists nivel_id    bigint references public.niveles_cargo(id) on delete set null;
alter table public.puestos add column if not exists descripcion text;
create index if not exists puestos_area_idx on public.puestos (area_id);

-- ------------------------------------------------------------------
-- 4. Rango salarial del cargo: tabla aparte porque "puestos" la leen todos los colaboradores.
--    Solo Admin de la misma empresa (igual que compensaciones).
-- ------------------------------------------------------------------
create table if not exists public.rangos_salariales_cargo (
  puesto_id   bigint primary key references public.puestos(id) on delete cascade,
  empresa_id  bigint not null,
  salario_min numeric(14, 2) check (salario_min is null or salario_min > 0),
  salario_max numeric(14, 2) check (salario_max is null or salario_max > 0),
  moneda      text not null default 'COP',
  updated_at  timestamptz not null default now(),
  constraint rangos_salariales_orden check (salario_min is null or salario_max is null or salario_min <= salario_max),
  constraint rangos_salariales_algo check (salario_min is not null or salario_max is not null)
);

alter table public.rangos_salariales_cargo enable row level security;
drop policy if exists rangos_cargo_admin_select on public.rangos_salariales_cargo;
drop policy if exists rangos_cargo_admin_insert on public.rangos_salariales_cargo;
drop policy if exists rangos_cargo_admin_update on public.rangos_salariales_cargo;
drop policy if exists rangos_cargo_admin_delete on public.rangos_salariales_cargo;
create policy rangos_cargo_admin_select on public.rangos_salariales_cargo
  for select to authenticated using (public.es_admin_de_empresa(empresa_id));
create policy rangos_cargo_admin_insert on public.rangos_salariales_cargo
  for insert to authenticated with check (
    public.es_admin_de_empresa(empresa_id)
    and exists (select 1 from public.puestos p where p.id = puesto_id and p.empresa_id = rangos_salariales_cargo.empresa_id)
  );
create policy rangos_cargo_admin_update on public.rangos_salariales_cargo
  for update to authenticated using (public.es_admin_de_empresa(empresa_id)) with check (public.es_admin_de_empresa(empresa_id));
create policy rangos_cargo_admin_delete on public.rangos_salariales_cargo
  for delete to authenticated using (public.es_admin_de_empresa(empresa_id));

-- ------------------------------------------------------------------
-- 5. Sin duplicados por mayúsculas, tildes o espacios (verificado al inicio).
--    Áreas: únicas por empresa. Cargos: únicos por empresa + área (los antiguos sin área cuentan como un grupo).
-- ------------------------------------------------------------------

create unique index if not exists areas_nombre_unico_idx
  on public.areas (empresa_id, public.normalizar_nombre(nombre));
create unique index if not exists puestos_nombre_unico_idx
  on public.puestos (empresa_id, coalesce(area_id, 0), public.normalizar_nombre(nombre));
