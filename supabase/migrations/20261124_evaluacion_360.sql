-- Evaluación 360 por ciclos (semestral o anual), con competencias, pares elegidos por el líder, anonimato por umbral,
-- calibración y entrega de resultados en una conversación 1:1.
-- Ejecutar una vez en Supabase → SQL Editor (después de 20261123_okr.sql).
--
-- Modelo:
--  * ev360_competencias / ev360_conductas: biblioteca editable de la empresa (grupo 'corporativa' = todos,
--    'liderazgo' = solo quienes tienen equipo). Cada conducta se califica de 1 a 5 o "no observado".
--  * ev360_ciclos: un corte. Al lanzarlo se congela el cuestionario (jsonb) para que editar la biblioteca no altere
--    ciclos en curso o pasados. estado: borrador → nominacion → evaluacion → calibracion → resultados → cerrado.
--  * ev360_participantes: cada persona evaluada en el ciclo, con su líder directo al momento del lanzamiento y la
--    entrega de resultados (conversación 1:1, acuerdos y reflexión de la persona).
--  * ev360_asignaciones: quién evalúa a quién (auto, lider, par, colaborador) y los comentarios cualitativos.
--  * ev360_respuestas: puntaje por conducta (null = no observado).
--  * ev360_calibraciones: ajuste del resultado de una competencia en la calibración, con justificación.
-- La tabla antigua public.evaluaciones se conserva intacta como histórico (modelo anterior).
-- Todo se lee y escribe desde el servidor (/api/evaluaciones) con la service role: RLS sin políticas.

create table if not exists public.ev360_competencias (
  id          bigint generated by default as identity primary key,
  empresa_id  bigint  not null,
  nombre      text    not null check (btrim(nombre) <> ''),
  descripcion text,
  grupo       text    not null default 'corporativa' check (grupo in ('corporativa', 'liderazgo')),
  activa      boolean not null default true,
  orden       integer not null default 0,
  created_at  timestamptz not null default now()
);
create index if not exists ev360_competencias_empresa_idx on public.ev360_competencias (empresa_id, orden);

create table if not exists public.ev360_conductas (
  id             bigint generated by default as identity primary key,
  competencia_id bigint  not null references public.ev360_competencias(id) on delete cascade,
  empresa_id     bigint  not null,
  texto          text    not null check (btrim(texto) <> ''),
  orden          integer not null default 0
);
create index if not exists ev360_conductas_competencia_idx on public.ev360_conductas (competencia_id, orden);

create table if not exists public.ev360_ciclos (
  id                bigint generated by default as identity primary key,
  empresa_id        bigint  not null,
  nombre            text    not null check (btrim(nombre) <> ''),
  frecuencia        text    not null default 'semestral' check (frecuencia in ('semestral', 'anual')),
  periodo_desde     date    not null,
  periodo_hasta     date    not null,
  nominacion_hasta  date,
  evaluacion_hasta  date,
  calibracion_hasta date,
  estado            text    not null default 'borrador'
                    check (estado in ('borrador', 'nominacion', 'evaluacion', 'calibracion', 'resultados', 'cerrado')),
  -- Peso de cada perspectiva en el resultado (la autoevaluación no suma: se usa para la brecha de percepción)
  peso_lider        smallint not null default 40 check (peso_lider between 0 and 100),
  peso_pares        smallint not null default 30 check (peso_pares between 0 and 100),
  peso_colaboradores smallint not null default 30 check (peso_colaboradores between 0 and 100),
  minimo_anonimato  smallint not null default 3 check (minimo_anonimato between 2 and 10),
  cuestionario      jsonb,
  lanzado_en        timestamptz,
  creado_por        uuid,
  created_at        timestamptz not null default now(),
  constraint ev360_ciclos_periodo check (periodo_hasta >= periodo_desde),
  constraint ev360_ciclos_pesos check (peso_lider + peso_pares + peso_colaboradores = 100)
);
create index if not exists ev360_ciclos_empresa_idx on public.ev360_ciclos (empresa_id, periodo_desde desc);

create table if not exists public.ev360_participantes (
  id              bigint generated by default as identity primary key,
  ciclo_id        bigint  not null references public.ev360_ciclos(id) on delete cascade,
  empresa_id      bigint  not null,
  evaluado_id     bigint  not null references public.empleados(id) on delete cascade,
  lider_id        bigint  references public.empleados(id) on delete set null,
  es_lider        boolean not null default false,
  conversado_en   timestamptz,
  conversado_por  bigint  references public.empleados(id) on delete set null,
  acuerdos        text,
  reflexion       text,
  reflexion_en    timestamptz,
  unique (ciclo_id, evaluado_id)
);
create index if not exists ev360_participantes_lider_idx on public.ev360_participantes (ciclo_id, lider_id);

create table if not exists public.ev360_asignaciones (
  id            bigint generated by default as identity primary key,
  ciclo_id      bigint  not null references public.ev360_ciclos(id) on delete cascade,
  empresa_id    bigint  not null,
  evaluado_id   bigint  not null references public.empleados(id) on delete cascade,
  evaluador_id  bigint  not null references public.empleados(id) on delete cascade,
  relacion      text    not null check (relacion in ('auto', 'lider', 'par', 'colaborador')),
  estado        text    not null default 'pendiente' check (estado in ('pendiente', 'completada')),
  fortaleza     text,
  consejo       text,
  completada_en timestamptz,
  asignada_por  bigint  references public.empleados(id) on delete set null,
  created_at    timestamptz not null default now(),
  unique (ciclo_id, evaluado_id, evaluador_id),
  constraint ev360_auto_coherente check ((relacion = 'auto') = (evaluado_id = evaluador_id))
);
create index if not exists ev360_asignaciones_evaluador_idx on public.ev360_asignaciones (ciclo_id, evaluador_id);
create index if not exists ev360_asignaciones_evaluado_idx on public.ev360_asignaciones (ciclo_id, evaluado_id);

create table if not exists public.ev360_respuestas (
  asignacion_id  bigint   not null references public.ev360_asignaciones(id) on delete cascade,
  -- Ids del cuestionario congelado del ciclo (no FK: la biblioteca puede cambiar)
  competencia_id bigint   not null,
  conducta_id    bigint   not null,
  puntaje        smallint check (puntaje is null or puntaje between 1 and 5),
  primary key (asignacion_id, conducta_id)
);

create table if not exists public.ev360_calibraciones (
  id             bigint generated by default as identity primary key,
  ciclo_id       bigint  not null references public.ev360_ciclos(id) on delete cascade,
  empresa_id     bigint  not null,
  evaluado_id    bigint  not null references public.empleados(id) on delete cascade,
  competencia_id bigint  not null,
  puntaje        numeric(3, 2) not null check (puntaje between 1 and 5),
  justificacion  text    not null check (btrim(justificacion) <> ''),
  ajustado_por   bigint  references public.empleados(id) on delete set null,
  created_at     timestamptz not null default now(),
  unique (ciclo_id, evaluado_id, competencia_id)
);

-- Una evaluación enviada no se modifica (tampoco sus respuestas)
create or replace function public.ev360_bloquear_enviada() returns trigger language plpgsql as $$
begin
  if tg_table_name = 'ev360_asignaciones' then
    if old.estado = 'completada' and (new.estado <> old.estado or new.fortaleza is distinct from old.fortaleza
       or new.consejo is distinct from old.consejo) then
      raise exception 'La evaluación ya fue enviada y no puede modificarse.';
    end if;
    return new;
  end if;
  if exists (select 1 from public.ev360_asignaciones a where a.id = old.asignacion_id and a.estado = 'completada') then
    raise exception 'La evaluación ya fue enviada y no puede modificarse.';
  end if;
  return new;
end $$;

drop trigger if exists ev360_asignaciones_bloqueo on public.ev360_asignaciones;
create trigger ev360_asignaciones_bloqueo before update on public.ev360_asignaciones
  for each row execute function public.ev360_bloquear_enviada();
drop trigger if exists ev360_respuestas_bloqueo on public.ev360_respuestas;
create trigger ev360_respuestas_bloqueo before update on public.ev360_respuestas
  for each row execute function public.ev360_bloquear_enviada();

alter table public.ev360_competencias  enable row level security;  -- sin políticas: solo el servidor
alter table public.ev360_conductas     enable row level security;
alter table public.ev360_ciclos        enable row level security;
alter table public.ev360_participantes enable row level security;
alter table public.ev360_asignaciones  enable row level security;
alter table public.ev360_respuestas    enable row level security;
alter table public.ev360_calibraciones enable row level security;
